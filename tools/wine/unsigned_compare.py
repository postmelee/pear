"""Compare complete unsigned Wine installs without hiding executable differences.

Raw identities are authoritative. Explanations apply only to parsed metadata
fields and exact recorded build-path substitutions in non-executable strings.
The in-memory coverage map never modifies either artifact or its recorded hash.
"""
from __future__ import annotations

import hashlib
from pathlib import Path
import re
import struct

from common import Error, encoded, load_json, need, read_relative, record, sha256

