def namespace_path_hash(path):
    """Selected Clang namespace tags use low32(XXH3-64(main-file path))."""
    need(17 <= len(path) <= 128, 'comparison_namespace_path_length')
    secret = bytes.fromhex(
        'b8fe6c3923a44bbe7c01812cf721ad1cded46de9839097db7240a4a4b7b3671f'
        'cb79e64eccc0e578825ad07dccff7221b8084674f743248ee03590e6813a264c'
        '3c2852bb91c300cb88d0658b1b532ea371644897a20df94e3819ef46a9deacd8'
        'a8fa763fe39c343ff9dcbbc7c70b4f1d8a51e04bcdb45931c89f7ec9d9787364')
    mask = (1 << 64) - 1
    total = len(path) * 0x9e3779b185ebca87
    rounds = 1 + int(len(path) > 32) + int(len(path) > 64) + int(len(path) > 96)
    for index in range(rounds):
        for offset, key in ((index * 16, index * 32), (len(path) - 16 * (index + 1), index * 32 + 16)):
            low = unpack(path, '<Q', offset)[0] ^ unpack(secret, '<Q', key)[0]
            high = unpack(path, '<Q', offset + 8)[0] ^ unpack(secret, '<Q', key + 8)[0]
            product = low * high
            total += (product & mask) ^ (product >> 64)
    total &= mask
    total ^= total >> 37
    total = (total * 0x165667919e3779f9) & mask
    return (total ^ (total >> 32)) & 0xffffffff


def namespace_sections(raw, pe):
    if not pe:
        return coff_structure(raw)[1]
    # A linked PE has many translation units. Only its real non-executable
    # .debug_str payload can establish their compiler path tags.
    info = symbol_info(raw, True)
    if info is None:
        return []
    header = unpack(raw, '<I', 60)[0] + 4
    count = unpack(raw, '<H', header + 2)[0]
    optional = unpack(raw, '<H', header + 16)[0]
    out = []
    names = dict(info['headers'])
    for index in range(count):
        at = header + 20 + optional + index * 40
        name = names.get(at, take(raw, at, 8).split(b'\0')[0])
        if name == b'.debug_str':
            offset, size, flags = info['sections'][index]
            need(offset and not flags & (0x20 | 0x20000000), 'comparison_debug_string_code')
            out.append({'name': name, 'offset': offset, 'flags': flags, 'data': take(raw, offset, size)})
    return out


def namespace_debug_names(old_sections, new_sections, path_pairs, old_symbols=(), new_symbols=(), *, linked=False):
    tables = [row['data'].split(b'\0') for row in old_sections if row['name'] == b'.debug_str']
    after_tables = [row['data'].split(b'\0') for row in new_sections if row['name'] == b'.debug_str']
    if not tables:
        return {}
    need(len(tables) == len(after_tables) == 1, 'comparison_namespace_tables')
    candidates = []
    for old in tables[0]:
        if old.endswith((b'.cpp', b'.cc', b'.cxx')) and b'/source/' in old:
            new = substitute(old, path_pairs)
            if new != old and new in after_tables[0]:
                candidates.append((old, new))
    if not candidates:
        return {}
    need(0 < len(candidates) <= (4096 if linked else 1), 'comparison_namespace_main_file')
    tags = {}
    for old_path, new_path in candidates:
        old_tag = b'?A0x' + format(namespace_path_hash(old_path), 'X').encode() + b'@'
        new_tag = b'?A0x' + format(namespace_path_hash(new_path), 'X').encode() + b'@'
        need(old_tag not in tags or tags[old_tag] == new_tag, 'comparison_namespace_tag_conflict')
        tags[old_tag] = new_tag
    result = {}
    available = set(after_tables[0]) | set(new_symbols)
    for text in [*tables[0], *old_symbols]:
        found = set(re.findall(rb'\?A0x[0-9A-F]+@', text)) & tags.keys()
        if found:
            mapped = text
            for tag in found:
                mapped = mapped.replace(tag, tags[tag])
            need(mapped in available, 'comparison_namespace_tag_binding')
            result[text] = mapped
    return result


def coff_structure(raw):
    """Inventory every COFF byte; selected objects have no line-number tables."""
    coff_regions(raw, pe=False)
    symbols = symbol_info(raw, False)
    need(symbols is not None, 'comparison_structural_symbols')
    _, count, _, table, symbol_count, optional, _ = unpack(raw, '<HHIIIHH', 0)
    need(optional == 0 and unpack(raw, '<H', 0)[0] == 0xaa64, 'comparison_structural_arm64_header')
    occupied = bytearray(len(raw))
    def own(offset, size):
        take(raw, offset, size)
        need(not any(occupied[offset:offset + size]), 'comparison_structural_overlap')
        occupied[offset:offset + size] = b'\1' * size
    own(0, 20 + count * 40)
    own(table, symbol_count * 18 + symbols['string_size'])
    sections = []
    for index in range(count):
        at = 20 + 40 * index
        name_field = take(raw, at, 8)
        name = name_field.split(b'\0')[0]
        need(name_field == name.ljust(8, b'\0'), 'comparison_section_name_padding')
        if name.startswith(b'/'):
            name = cstring(raw, symbols['strings'] + int(name[1:]),
                           symbols['strings'] + symbols['string_size'])
        virtual_size, address, size, offset, relocations, lines, nreloc, nlines, flags = unpack(raw, '<IIIIIIHHI', at + 8)
        need(lines == 0 and nlines == 0 and not flags & 0x01000000,
             'comparison_structural_lines_or_overflow')
        need(nreloc or relocations == 0, 'comparison_structural_unused_relocation_pointer')
        data = take(raw, offset, size) if offset else b''
        if offset: own(offset, size)
        if nreloc: own(relocations, nreloc * 10)
        relocation_rows = [unpack(raw, '<IIH', relocations + n * 10) for n in range(nreloc)]
        sections.append({'name': name, 'offset': offset, 'size': size, 'data': data,
                         'virtual_size': virtual_size, 'address': address, 'flags': flags,
                         'relocations': relocation_rows, 'relocation_offset': relocations,
                         'header': take(raw, at, 40)})
    need(all(used or byte == 0 for byte, used in zip(raw, occupied)), 'comparison_structural_unknown_gap')
    return symbols, sections


def structural_literal_names(before, after, left, right, old_sections, new_sections, path_pairs):
    need(left['count'] == right['count'] and len(left['records']) == len(right['records']),
         'comparison_structural_symbol_count')
    names = {}
    namespace_names = namespace_debug_names(old_sections, new_sections, path_pairs,
        [row[1] for row in left['records']], [row[1] for row in right['records']])
    for a, b in zip(left['records'], right['records']):
        _, name, value, section, kind, storage, aux, long_name = a
        need(a[2:] == b[2:], 'comparison_structural_symbol_semantics')
        if name != b[1] and namespace_names.get(name) == b[1]:
            names[name] = b[1]
        elif name != b[1]:
            need(name.startswith((b'??_C@_0', b'??_C@_1')) and name[:7] == b[1][:7]
                 and 1 <= section <= len(old_sections), 'comparison_structural_symbol_name')
            x, y = old_sections[section - 1], new_sections[section - 1]
            need(not x['flags'] & (0x20 | 0x20000000) and value < len(x['data'])
                 and value < len(y['data']), 'comparison_structural_literal_section')
            wide = name.startswith(b'??_C@_1')
            old = literal_at(x['data'], value, len(x['data']), wide)
            new = literal_at(y['data'], value, len(y['data']), wide)
            need(old != new and substitute(old, path_pairs) == new
                 and msvc_literal_name(old, wide) == name and msvc_literal_name(new, wide) == b[1],
                 'comparison_structural_literal_binding')
            need(name not in names or names[name] == b[1], 'comparison_structural_literal_conflict')
            names[name] = b[1]
        # Section definitions carry independently checked length/checksum fields.
        old_aux, new_aux = take(before, a[0] + 18, 18 * aux), take(after, b[0] + 18, 18 * aux)
        if old_aux != new_aux:
            import zlib
            need(aux == 1 and value == 0 and kind == 0 and storage == 3 and 1 <= section <= len(old_sections)
                 and name == b[1] and old_aux[4:8] == new_aux[4:8] and old_aux[12:] == new_aux[12:],
                 'comparison_structural_symbol_auxiliary')
            for raw_aux, row in ((old_aux, old_sections[section - 1]), (new_aux, new_sections[section - 1])):
                need(unpack(raw_aux, '<I', 0)[0] == row['size'] and row['offset']
                     and unpack(raw_aux, '<I', 8)[0] == zlib.crc32(row['data'], 0xffffffff) ^ 0xffffffff,
                     'comparison_structural_section_checksum')
    # The complete COFF name tables, including unreferenced strings, stay bound.
    old_names = take(before, left['strings'] + 4, left['string_size'] - 4)
    new_names = take(after, right['strings'] + 4, right['string_size'] - 4)
    need(old_names.endswith(b'\0') and new_names.endswith(b'\0')
         and sorted(names.get(s, s) for s in old_names.split(b'\0')) == sorted(new_names.split(b'\0')),
         'comparison_structural_name_table')
    return names


def compare_coff_alignment(before, after, path, path_pairs):
    """Handle selected COFF debug-string size changes by complete section replay."""
    before, after = bytes(before), bytes(after)
    result = {'before_sha256': digest(before), 'after_sha256': digest(after),
              'before_size_bytes': len(before), 'after_size_bytes': len(after),
              'comparison_mode': 'coff_section_alignment', 'difference_runs': [], 'explained_regions': []}
    try:
        left, old = coff_structure(before); right, new = coff_structure(after)
        need(len(old) == len(new) and take(before, 0, 4) == take(after, 0, 4)
             and take(before, 12, 8) == take(after, 12, 8), 'comparison_structural_header')
        for a, b in zip(old, new):
            if not a['size'] or not b['size']:
                need(a['offset'] == b['offset'], 'comparison_structural_unused_data_pointer')
            for key in ('name', 'virtual_size', 'address', 'flags', 'relocations'):
                need(a[key] == b[key], 'comparison_structural_section_identity')
            if a['size'] != b['size']:
                need(a['name'] == b'.debug_str' and not a['flags'] & (0x20 | 0x20000000),
                     'comparison_structural_nondebug_size')
        names = structural_literal_names(before, after, left, right, old, new, path_pairs)
        namespace_names = namespace_debug_names(old, new, path_pairs)
        need(all(names[k] == namespace_names[k] for k in names.keys() & namespace_names.keys()),
             'comparison_debug_name_conflict')
        debug_names = {**names, **namespace_names}
        # Each actual string is compared in order, with only already-bound names
        # and exact recorded path substitutions. No debug string is dropped.
        for a, b in zip(old, new):
            if a['name'] == b'.debug_str':
                need(not a['flags'] & (0x20 | 0x20000000), 'comparison_debug_string_code')
                need(a['data'].endswith(b'\0') and b['data'].endswith(b'\0'),
                     'comparison_debug_strings_terminated')
                expected = [substitute(debug_names.get(s, s), path_pairs) for s in a['data'].split(b'\0')]
                need(expected == b['data'].split(b'\0'), 'comparison_debug_string_contents')
        records = {int((row[0] - left['table']) // 18): row for row in left['records']}
        sections = []
        for index, (a, b) in enumerate(zip(old, new)):
            old_data, new_data = a['data'], b['data']
            accepted = []
            if a['name'] != b'.debug_str':
                need(len(old_data) == len(new_data), 'comparison_structural_section_size')
                if not a['flags'] & (0x20 | 0x20000000) and a['name'] in (b'.rdata', b'.debug_line', b'.debug_info'):
                    path_regions(old_data, new_data, [(0, len(old_data), 'recorded-build-path-string')], path_pairs, accepted)
                for address, symbol_index, kind in a['relocations']:
                    need(symbol_index in records, 'comparison_structural_relocation_symbol')
                    symbol = records[symbol_index]
                    target_section = symbol[3] - 1
                    if kind == 8 and 0 <= target_section < len(old) and old[target_section]['name'] == b'.debug_str':
                        need(not a['flags'] & (0x20 | 0x20000000) and a['name'] in (b'.debug_info', b'.debug_line'),
                             'comparison_structural_debug_reference_code')
                        x, y = old[target_section]['data'], new[target_section]['data']
                        old_at = symbol[2] + unpack(old_data, '<I', address)[0]
                        new_at = symbol[2] + unpack(new_data, '<I', address)[0]
                        old_text, new_text = cstring(x, old_at, len(x)), cstring(y, new_at, len(y))
                        need(substitute(debug_names.get(old_text, old_text), path_pairs) == new_text,
                             'comparison_structural_debug_reference')
                        accepted.append((address, 4, 'coff-verified-debug-string-reference'))
                check = bytearray(old_data)
                for offset, size, _ in accepted:
                    check[offset:offset + size] = take(new_data, offset, size)
                need(bytes(check) == new_data, 'comparison_structural_section_bytes')
            sections.append({'ordinal': index, 'name': a['name'].decode('ascii'),
                             'before_offset': a['offset'], 'after_offset': b['offset'],
                             'before_size_bytes': len(old_data), 'after_size_bytes': len(new_data),
                             'before_sha256': digest(old_data), 'after_sha256': digest(new_data),
                             'before_header_sha256': digest(a['header']), 'after_header_sha256': digest(b['header']),
                             'relocations_sha256': digest(encoded(a['relocations'])),
                             'status': 'exact' if old_data == new_data else 'explained_metadata',
                             'verified_ranges': [[p, n, policy] for p, n, policy in accepted],
                             'debug_string_table_verified': a['name'] == b'.debug_str'})
        result.update(status='explained_metadata', coff_sections=sections,
                      before_symbols_sha256=digest(before[left['table']:]),
                      after_symbols_sha256=digest(after[right['table']:]),
                      all_file_bytes_accounted=True,
                      changed_bytes=sum(a != b for a, b in zip(before, after)) + abs(len(before) - len(after)))
        return result, names
    except (Error, ValueError, struct.error) as exc:
        result.update(status='unexplained', reason=getattr(exc, 'code', 'comparison_coff_alignment_invalid'),
                      changed_bytes=None, all_file_bytes_accounted=False)
        return result, {}


def archive_members(raw):
    need(take(raw, 0, 8) == b'!<arch>\n', 'comparison_archive_magic')
    rows, offset = [], 8
    while offset < len(raw):
        header = take(raw, offset, 60)
        need(header[58:] == b'`\n' and header[48:58].strip().isdigit(), 'comparison_archive_header')
        size = int(header[48:58].strip())
        payload = take(raw, offset + 60, size)
        padding = take(raw, offset + 60 + size, size & 1)
        need(not padding or padding == b'\n', 'comparison_archive_padding')
        rows.append((offset, header, payload))
        need(len(rows) <= 4096, 'comparison_archive_member_budget')
        offset += 60 + size + (size & 1)
    need(offset == len(raw), 'comparison_archive_length')
    return rows


def terminal_coff_pair(before, after):
    left, right = symbol_info(before, False), symbol_info(after, False)
    need(left is not None and right is not None, 'comparison_terminal_symbols_missing')
    for key in ('table', 'count', 'strings', 'sections'):
        need(left[key] == right[key], 'comparison_terminal_layout_changed')
    for raw, info in ((before, left), (after, right)):
        end = info['strings'] + info['string_size']
        need(end <= len(raw) <= end + 3 and not any(raw[end:]), 'comparison_terminal_symbol_padding')
    size = max(len(before), len(after))
    return before.ljust(size, b'\0'), after.ljust(size, b'\0')


def archive_index_entries(raw, ordinal):
    if ordinal == 0:
        count = unpack(raw, '>I', 0)[0]
        need(count <= 1000000, 'comparison_archive_index_budget')
        offset, entries = 4 + count * 4, []
        for index in range(count):
            member = unpack(raw, '>I', 4 + index * 4)[0]
            name = cstring(raw, offset, len(raw))
            entries.append((member, name)); offset += len(name) + 1
        need(not any(raw[offset:]), 'comparison_archive_index_padding')
        return entries, None
    members = unpack(raw, '<I', 0)[0]
    need(members <= 4096, 'comparison_archive_index_member_budget')
    addresses = [unpack(raw, '<I', 4 + i * 4)[0] for i in range(members)]
    start = 4 + members * 4
    count = unpack(raw, '<I', start)[0]
    need(count <= 1000000, 'comparison_archive_index_budget')
    offset, entries = start + 4 + 2 * count, []
    for index in range(count):
        member = unpack(raw, '<H', start + 4 + 2 * index)[0]
        need(1 <= member <= members, 'comparison_archive_sorted_reference')
        name = cstring(raw, offset, len(raw))
        entries.append((addresses[member - 1], name)); offset += len(name) + 1
    need(not any(raw[offset:]) and [name for _, name in entries] == sorted(name for _, name in entries),
         'comparison_archive_sorted_names')
    return entries, addresses


def ledger_size(row):
    return (len(row.get('difference_runs', [])) + len(row.get('explained_regions', []))
            + sum(1 + len(section['verified_ranges']) for section in row.get('coff_sections', []))
            + sum(1 + ledger_size(member['comparison']) for member in row.get('archive_members', [])))


def compare_archive_alignment(before, after, path, path_pairs):
    """Prove every relocated member, header and both indexes; do not strip data."""
    result = {'before_sha256': digest(before), 'after_sha256': digest(after),
              'before_size_bytes': len(before), 'after_size_bytes': len(after),
              'comparison_mode': 'archive_member_alignment', 'difference_runs': [],
              'explained_regions': []}
    try:
        old, new = archive_members(before), archive_members(after)
        need(len(old) == len(new), 'comparison_archive_member_count')
        mapping = {a[0]: b[0] for a, b in zip(old, new)}
        ordinary_offsets = {a[0] for a in old if a[1][:16].strip() not in (b'/', b'//')}
        names, rows, indices = {}, [], []
        for index, (a, b) in enumerate(zip(old, new)):
            need(a[1][:48] == b[1][:48] and a[1][58:] == b[1][58:], 'comparison_archive_member_identity')
            name = a[1][:16].strip()
            if name == b'/':
                indices.append((index, a, b)); continue
            if a[2][:2] in (b'\x64\xaa', b'\x41\xa6', b'\x4e\xa6', b'\x64\x86', b'\x4c\x01'):
                if len(a[2]) != len(b[2]):
                    compared, mapped = compare_coff_alignment(a[2], b[2], path, path_pairs)
                    need(compared['status'] != 'unexplained', compared.get('reason', 'comparison_archive_coff'))
                else:
                    compared = compare_bytes(a[2], b[2], 'coff', path, path_pairs)
                    # Revalidate metadata before accepting index-name remapping.
                    coff_regions(a[2], pe=False); coff_regions(b[2], pe=False)
                    _, mapped = symbol_explanations(a[2], b[2], False, path_pairs)
                names.update({(a[0], name): value for name, value in mapped.items()})
            else:
                need(a[2] == b[2], 'comparison_archive_unknown_member_change')
                compared = compare_bytes(a[2], b[2], 'data', path, ())
            rows.append({'ordinal': index, 'name': name.decode('ascii'),
                         'before_offset': a[0], 'after_offset': b[0],
                         'before_header_sha256': digest(a[1]), 'after_header_sha256': digest(b[1]),
                         'comparison': compared})
        need(len(indices) <= 2, 'comparison_archive_index_count')
        for ordinal, (index, a, b) in enumerate(indices):
            left, left_members = archive_index_entries(a[2], ordinal)
            right, right_members = archive_index_entries(b[2], ordinal)
            need(all(address in ordinary_offsets for address, _ in left), 'comparison_archive_index_member')
            expected = [(mapping[address], names.get((address, name), name)) for address, name in left]
            if ordinal == 0:
                need(expected == right, 'comparison_archive_relocated_index')
            else:
                need(all(address in ordinary_offsets for address in left_members)
                     and [mapping[x] for x in left_members] == right_members
                     and sorted(expected) == sorted(right), 'comparison_archive_relocated_sorted_index')
            child = {'before_sha256': digest(a[2]), 'after_sha256': digest(b[2]),
                     'before_size_bytes': len(a[2]), 'after_size_bytes': len(b[2]),
                     'status': 'exact' if a[2] == b[2] else 'explained_metadata',
                     'comparison_mode': 'verified_archive_symbol_index',
                     'entries': len(left), 'policy_id': 'coff-bound-archive-symbol-index',
                     'difference_runs': [], 'explained_regions': []}
            rows.append({'ordinal': index, 'name': '/', 'before_offset': a[0], 'after_offset': b[0],
                         'before_header_sha256': digest(a[1]), 'after_header_sha256': digest(b[1]),
                         'comparison': child})
        rows.sort(key=lambda row: row['ordinal'])
        result.update(archive_members=rows, archive_indices_verified=True,
                      changed_bytes=sum(a != b for a, b in zip(before, after)) + abs(len(before) - len(after)),
                      status='unexplained' if any(row['comparison']['status'] == 'unexplained' for row in rows)
                      else 'explained_metadata')
        need(ledger_size(result) <= MAX_FILE_RUNS, 'comparison_archive_ledger_budget')
    except (Error, ValueError, struct.error) as exc:
        result.update(status='unexplained', reason=getattr(exc, 'code', 'comparison_archive_invalid'),
                      changed_bytes=None, archive_indices_verified=False)
    return result


def compare_bytes(before, after, kind, path, path_pairs=()):
    """A malformed or unclassified difference remains an explicit failed row."""
    need(len(before) <= MAX_ARTIFACT and len(after) <= MAX_ARTIFACT, 'comparison_artifact_budget')
    before, after = bytes(before), bytes(after)
    result = {'before_sha256': digest(before), 'after_sha256': digest(after),
              'before_size_bytes': len(before), 'after_size_bytes': len(after)}
    if before == after:
        return {**result, 'status': 'exact', 'changed_bytes': 0, 'difference_runs': [], 'explained_regions': []}
    raw_before, raw_after = before, after
    if before.startswith(b'!<arch>\n') and after.startswith(b'!<arch>\n'):
        try:
            left, right = archive_members(before), archive_members(after)
            shifted = len(left) != len(right) or any(a[:2] != b[:2] for a, b in zip(left, right))
        except Error:
            shifted = True
        if shifted:
            return compare_archive_alignment(before, after, path, path_pairs)
    if len(before) != len(after):
        try:
            need(kind == 'coff', 'size_changed')
            before, after = terminal_coff_pair(before, after)
            result['comparison_mode'] = 'coff_terminal_string_table'
        except (Error, ValueError, struct.error) as exc:
            return {**result, 'status': 'unexplained', 'reason': getattr(exc, 'code', 'size_changed'),
                    'changed_bytes': None, 'difference_runs': [], 'explained_regions': []}
    accepted, error = [], None
    try:
        old_fields, old_strings = parsed_regions(before, kind, path)
        new_fields, new_strings = parsed_regions(after, kind, path)
        need(old_fields == new_fields and old_strings == new_strings, 'comparison_format_layout_changed')
        accepted.extend(old_fields)
        if kind in ('pe', 'pe_metadata', 'coff'):
            spans, _ = symbol_explanations(before, after, kind != 'coff', path_pairs)
            accepted.extend(spans)
        elif before.startswith(b'!<arch>\n'):
            accepted.extend(archive_symbol_explanations(before, after, path_pairs))
        path_regions(before, after, old_strings, path_pairs, accepted)
        if kind in ('coff', 'pe', 'pe_metadata'):
            old_sections = namespace_sections(before, kind != 'coff')
            new_sections = namespace_sections(after, kind != 'coff')
            namespace_names = namespace_debug_names(old_sections, new_sections, path_pairs, linked=kind != 'coff')
            for left_section, right_section in zip(old_sections, new_sections):
                if left_section['name'] != b'.debug_str':
                    continue
                need(not left_section['flags'] & (0x20 | 0x20000000), 'comparison_debug_string_code')
                for old_name, new_name in namespace_names.items():
                    start = 0
                    while True:
                        start = left_section['data'].find(old_name + b'\0', start)
                        if start < 0:
                            break
                        need((start == 0 or left_section['data'][start - 1] == 0)
                             and len(old_name) == len(new_name)
                             and take(right_section['data'], start, len(new_name) + 1) == new_name + b'\0',
                             'comparison_namespace_string_position')
                        accepted.append((left_section['offset'] + start, len(old_name), 'coff-bound-symbol-string-table'))
                        start += len(old_name) + 1
    except (Error, ValueError, struct.error) as exc:
        error = getattr(exc, 'code', 'comparison_format_invalid')
        accepted = []
    coverage = bytearray(len(before))
    for start, size, policy in accepted:
        coverage[start:start + size] = bytes([POLICIES.index(policy) + 1]) * size
    # Known metadata is recorded as complete typed regions with both raw hashes.
    # Unexplained changes retain individual byte runs. This checks every byte
    # without allocating millions of runs for a reordered COFF string table.
    runs, regions, changed, active, region_start, region_changes = [], [], 0, None, 0, 0
    region_code = coverage[0] if coverage else 0
    def finish_region(stop):
        if region_code and region_changes:
            regions.append([region_start, stop - region_start, region_code, region_changes,
                            digest(raw_before[region_start:stop]), digest(raw_after[region_start:stop])])
    for i, (a, b) in enumerate(zip(before, after)):
        code = coverage[i]
        if code != region_code:
            finish_region(i)
            region_start, region_code, region_changes = i, code, 0
        different = a != b
        if different:
            changed += 1
            region_changes += 1
        if active is not None and (not different or code != 0):
            runs.append([active, i - active, 0])
            if len(runs) >= MAX_FILE_RUNS:
                return {**result, 'status': 'unexplained', 'reason': 'difference_budget_exceeded',
                        'format_error': error, 'changed_bytes': None, 'difference_runs': [], 'explained_regions': []}
            active = None
        if different and code == 0 and active is None:
            active = i
    finish_region(len(before))
    if active is not None:
        runs.append([active, len(before) - active, 0])
    need(len(regions) <= MAX_FILE_RUNS, 'comparison_region_budget')
    result.update(status='unexplained' if runs else 'explained_metadata',
                  changed_bytes=changed, difference_runs=runs, explained_regions=regions)
    if error:
        result['reason'] = error
    return result


def compare_unsigned(reference_root, candidate_root):
    """Reverify both complete builds and compare every installed ordinary file."""
    from build import artifact_inventory, source_argument_policy, verify_build
    roots = [Path(reference_root).resolve(), Path(candidate_root).resolve()]
    need(roots[0] != roots[1], 'comparison_same_build')
    builds = [verify_build(roots[0], current=False), verify_build(roots[1])]
    need(all(row['variant'] == 'arm64' for row in builds), 'comparison_native_variants')
    need(source_argument_policy(builds[0]) == source_argument_policy(builds[1]),
         'comparison_source_argument_policy')
    for key in ('record_hashes', 'source_manifest', 'patches', 'fixture_hashes', 'sdk',
                'tool_prepared_sha256', 'configuration', 'fixture_suite', 'code_publication_policy'):
        need(builds[0][key] == builds[1][key], 'comparison_inputs_differ')
    inventories = [artifact_inventory(b, r) for b, r in zip(builds, roots)]
    tables = [{r['path']: r for r in value['files']} for value in inventories]
    need(all(len(t) == len(i['files']) for t, i in zip(tables, inventories)), 'comparison_duplicate_path')
    need(all(len(t) <= 8192 for t in tables), 'comparison_inventory_budget')
    pairs = mappings(*builds, *roots)
    total_runs = 0
    rows, missing, extra, changed_metadata = [], sorted(tables[0].keys() - tables[1].keys()), sorted(tables[1].keys() - tables[0].keys()), []
    for path in sorted(tables[0].keys() & tables[1].keys()):
        left, right = tables[0][path], tables[1][path]
        metadata = [{k: v for k, v in row.items() if k not in ('sha256', 'size_bytes')} for row in (left, right)]
        if metadata[0] != metadata[1]:
            changed_metadata.append(path)
        before, after = [read_relative(root / 'install', path, MAX_ARTIFACT) for root in roots]
        need(digest(before) == left['sha256'] and digest(after) == right['sha256'], 'comparison_artifact_changed')
        row = compare_bytes(before, after, left['kind'], path, pairs)
        total_runs += ledger_size(row)
        need(total_runs <= MAX_TOTAL_RUNS, 'comparison_total_difference_budget')
        rows.append({'path': path, 'kind': left['kind'], 'before_mode': left['mode'],
                     'after_mode': right['mode'], **row})
    counts = {name + '_files': sum(row['status'] == name for row in rows)
              for name in ('exact', 'explained_metadata', 'unexplained')}
    links_equal = inventories[0]['symlinks'] == inventories[1]['symlinks']
    passed = not (missing or extra or changed_metadata or counts['unexplained_files']) and links_equal
    return {'schema_version': 1, 'record_kind': 'wine_unsigned_comparison',
            'scope': 'complete_native_unsigned_install', 'policy_ids': list(POLICIES),
            'reference_build_sha256': sha256(roots[0] / 'build.json'),
            'candidate_build_sha256': sha256(roots[1] / 'build.json'),
            'reference_inventory_sha256': builds[0]['artifacts_manifest']['sha256'],
            'candidate_inventory_sha256': builds[1]['artifacts_manifest']['sha256'],
            'reference_files': len(tables[0]), 'candidate_files': len(tables[1]),
            'missing_paths': missing, 'extra_paths': extra, 'metadata_changed_paths': changed_metadata,
            'reference_symlinks': inventories[0]['symlinks'], 'candidate_symlinks': inventories[1]['symlinks'],
            'symlinks_equal': links_equal, **counts, 'files': rows,
            'byte_identity': passed and not counts['explained_metadata_files'], 'gate_passed': passed,
            'signed_byte_identity_claimed': False}


def validate_unsigned_comparison(path, reference_root, candidate_root):
    from common import decode_json
    path = Path(path).absolute()
    raw = read_relative(path.parent, path.name, MAX_COMPARISON)
    value = record(decode_json(raw, max_bytes=MAX_COMPARISON,
                              max_nodes=2000000), 'wine_unsigned_comparison')
    expected = compare_unsigned(reference_root, candidate_root)
    need(encoded(value) == encoded(expected), 'comparison_record_mismatch')
    return value


def public_summary(value):
    """Only a recomputed record should reach this explicit public allowlist."""
    keys = ('reference_build_sha256', 'candidate_build_sha256', 'reference_inventory_sha256',
            'candidate_inventory_sha256', 'reference_files', 'candidate_files',
            'exact_files', 'explained_metadata_files', 'unexplained_files',
            'symlinks_equal', 'byte_identity', 'gate_passed', 'signed_byte_identity_claimed', 'policy_ids')
    return {**{key: value[key] for key in keys}, 'comparison_sha256': digest(encoded(value)),
            'missing_files': len(value['missing_paths']), 'extra_files': len(value['extra_paths']),
            'metadata_changed_files': len(value['metadata_changed_paths'])}
